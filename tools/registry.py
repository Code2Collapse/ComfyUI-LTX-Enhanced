"""Research registry: the JSON files are the record, the Markdown tables are rendered from them.

    python tools/registry.py render    # rewrite the Markdown tables from the JSON files
    python tools/registry.py check     # exit 1 if a table is out of date or a row lacks licence / revision
    python tools/registry.py drift     # read-only: compare each recorded revision with the repo's HEAD (gh CLI)

Standard library only.
"""
from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCES = ROOT / "docs" / "registry" / "sources.json"
MODELS = ROOT / "docs" / "registry" / "models.json"
ISSUES = ROOT / "docs" / "registry" / "known_issues.json"
PAPERS = ROOT / "docs" / "papers" / "papers.json"

CATEGORY_TITLES = {
    "official": "Official Lightricks repositories",
    "core": "ComfyUI core (run-time host)",
    "tiling": "Tiled sampling and upscaling",
    "ltx-community": "Community LTX nodes",
    "acceleration": "Caching and attention acceleration",
    "quantisation": "Quantisation and offloading",
    "sampling": "Samplers and schedules",
    "other-model": "Other video stacks (method sources)",
}
GENERATED = "<!-- Generated by tools/registry.py from {src}. Edit the JSON, then run `python tools/registry.py render`. -->"


def _load(p: Path) -> dict:
    return json.loads(p.read_text(encoding="utf-8"))


def _cell(s) -> str:
    return str(s if s is not None else "").replace("|", "\\|").replace("\n", " ")


def render_sources(d: dict) -> str:
    out = ["# Ecosystem registry", "", GENERATED.format(src="docs/registry/sources.json"), "",
           f"Checked {d['checked']} with `{d['method']}`. A revision is the default-branch HEAD on that day: the "
           "code any behaviour note refers to. **Reuse** is what this Apache-2.0 pack may take from the repo; "
           "[the licence register](../licensing/register.md) explains each rule.", ""]
    for cat, title in CATEGORY_TITLES.items():
        rows = [r for r in d["sources"] if r["category"] == cat]
        if not rows:
            continue
        out += [f"## {title}", "", "| Repository | Revision | Licence | Reuse | What we study there |",
                "|---|---|---|---|---|"]
        for r in rows:
            rev = f"`{r['revision'][:10]}` {r['revision_date']}" + (" (archived)" if r.get("archived") else "")
            out.append(f"| [{_cell(r['repo'])}]({r['url']}) | {rev} | {_cell(r['licence'])} | {_cell(r['reuse'])} "
                       f"| {_cell(r['studies'])} |")
        out.append("")
    return "\n".join(out)


def render_models(d: dict) -> str:
    out = ["# Lightricks model registry", "", GENERATED.format(src="docs/registry/models.json"), "",
           f"Checked {d['checked']} with `{d['method']}`. {d['note']}", ""]
    for fam in dict.fromkeys(r["family"] for r in d["models"]):
        rows = [r for r in d["models"] if r["family"] == fam]
        out += [f"## {fam}", "", "| Repository | Kind | Licence (model card) | Last modified | Task |", "|---|---|---|---|---|"]
        for r in rows:
            out.append(f"| [{_cell(r['id'])}](https://huggingface.co/{r['id']}) | {r['kind']} | {_cell(r['licence'])} "
                       f"| {r['modified']} | {_cell(r['pipeline'] or '')} |")
        out.append("")
    return "\n".join(out)


def render_issues(d: dict) -> str:
    out = ["# Known upstream issues", "", GENERATED.format(src="docs/registry/known_issues.json"), "",
           f"Checked {d['checked']}: {d['method']}.", "", f"{d['note']}", ""]
    areas = dict.fromkeys(r["area"] for r in d["issues"])
    for a in areas:
        out += [f"## {a.capitalize()}", "", "| Issue | State | Title | What it means for this pack |", "|---|---|---|---|"]
        for r in (x for x in d["issues"] if x["area"] == a):
            url = f"https://github.com/{r['repo']}/issues/{r['number']}"
            out.append(f"| [#{r['number']}]({url}) | {r['state']} | {_cell(r['title'])} | {_cell(r['why'])} |")
        out.append("")
    return "\n".join(out)


def render_papers(d: dict) -> str:
    out = ["# Papers", "", GENERATED.format(src="docs/papers/papers.json"), "",
           f"Checked {d['checked']}: {d['method']}. The relevance notes come from the abstracts; nothing here is "
           "reproduced yet. Claims become benchmark items before any of them reaches a node.", ""]
    topics = dict.fromkeys(p["topic"] for p in d["papers"])
    for t in topics:
        out += [f"## {t.capitalize()}", "", "| arXiv | First version | Title | Why it matters here |", "|---|---|---|---|"]
        for p in (x for x in d["papers"] if x["topic"] == t):
            out.append(f"| [{p['arxiv']}](https://arxiv.org/abs/{p['arxiv']}) | {p['date']} | {_cell(p['title'])} "
                       f"| {_cell(p['why'])} |")
        out.append("")
    return "\n".join(out)


TARGETS = [
    (SOURCES, ROOT / "docs" / "registry" / "ecosystem.md", render_sources),
    (MODELS, ROOT / "docs" / "registry" / "models.md", render_models),
    (ISSUES, ROOT / "docs" / "registry" / "known_issues.md", render_issues),
    (PAPERS, ROOT / "docs" / "papers" / "README.md", render_papers),
]


def problems() -> list[str]:
    bad = []
    for r in _load(SOURCES)["sources"]:
        for k in ("licence", "reuse", "revision", "revision_date", "url", "category"):
            if not r.get(k):
                bad.append(f"sources.json {r.get('repo')}: missing {k}")
        if r.get("category") not in CATEGORY_TITLES:
            bad.append(f"sources.json {r.get('repo')}: unknown category {r.get('category')}")
    for m in _load(MODELS)["models"]:
        if not m.get("licence"):
            bad.append(f"models.json {m.get('id')}: missing licence")
    for p in _load(PAPERS)["papers"]:
        if not (p.get("arxiv") and p.get("title") and p.get("date")):
            bad.append(f"papers.json {p}: missing arxiv / title / date")
    for src, dst, fn in TARGETS:
        want = fn(_load(src)) + "\n"
        have = dst.read_text(encoding="utf-8") if dst.exists() else ""
        if have.replace("\r\n", "\n") != want:
            bad.append(f"{dst.relative_to(ROOT).as_posix()} is out of date: run `python tools/registry.py render`")
    return bad


def drift() -> int:
    changed = 0
    for r in _load(SOURCES)["sources"]:
        res = subprocess.run(["gh", "api", f"repos/{r['repo']}/commits/{r['default_branch']}", "--jq", ".sha"],
                             capture_output=True, text=True)
        head = res.stdout.strip() if res.returncode == 0 else f"error: {res.stderr.strip()[:80]}"
        if head != r["revision"]:
            changed += 1
            print(f"{r['repo']}: recorded {r['revision'][:10]} ({r['revision_date']}), now {head[:10]}")
    print(f"{changed} of {len(_load(SOURCES)['sources'])} repositories moved since they were recorded")
    return 0


def main(argv: list[str]) -> int:
    cmd = argv[1] if len(argv) > 1 else "check"
    if cmd == "render":
        for src, dst, fn in TARGETS:
            dst.write_text(fn(_load(src)) + "\n", encoding="utf-8", newline="\n")
            print(f"wrote {dst.relative_to(ROOT).as_posix()}")
        return 0
    if cmd == "check":
        bad = problems()
        for b in bad:
            print(b)
        print("registry ok" if not bad else f"{len(bad)} registry problem(s)")
        return 1 if bad else 0
    if cmd == "drift":
        return drift()
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv))
